#!/usr/bin/env bash
# Deploy Dify on the target server using images from Nexus.
#
# Intended to run over SSH from Azure DevOps (or manually on the server).
#
# Required environment:
#   DEPLOY_PATH              Git checkout path (default: /opt/Dify)
#   DIFY_API_IMAGE           e.g. nexus.example.com:8082/dify/dify-api
#   DIFY_WEB_IMAGE           e.g. nexus.example.com:8082/dify/dify-web
#   DIFY_API_IMAGE_TAG       commit-based tag from CI
#   DIFY_WEB_IMAGE_TAG       commit-based tag from CI
#
# Optional:
#   COMPOSE_FILE             Compose flags (default: -f docker-compose.yaml -f docker-compose.local-build.yaml)
#   GIT_PULL                 true|false — ff-only pull before deploy (default: true)
#   DEPLOY_SERVICES          space-separated services to recreate (default: api api_websocket worker worker_beat web)
#   NEXUS_USERNAME / NEXUS_USER   registry login user (either name works)
#   NEXUS_PASSWORD
#
# Usage (on server):
#   export DIFY_API_IMAGE=...
#   export DIFY_WEB_IMAGE=...
#   export DIFY_API_IMAGE_TAG=abc123
#   export DIFY_WEB_IMAGE_TAG=abc123
#   ./docker/deploy-remote.sh

set -euo pipefail

DEPLOY_PATH="${DEPLOY_PATH:-/opt/Dify}"
DOCKER_DIR="${DEPLOY_PATH}/docker"
TAG_FILE="${DOCKER_DIR}/.build-tag.env"
GIT_PULL="${GIT_PULL:-true}"
COMPOSE_FILE="${COMPOSE_FILE:--f docker-compose.yaml -f docker-compose.local-build.yaml}"
DEPLOY_SERVICES="${DEPLOY_SERVICES:-api api_websocket worker worker_beat web}"

: "${DIFY_API_IMAGE:?DIFY_API_IMAGE is required}"
: "${DIFY_WEB_IMAGE:?DIFY_WEB_IMAGE is required}"
: "${DIFY_API_IMAGE_TAG:?DIFY_API_IMAGE_TAG is required}"
: "${DIFY_WEB_IMAGE_TAG:?DIFY_WEB_IMAGE_TAG is required}"

NEXUS_USERNAME="${NEXUS_USERNAME:-${NEXUS_USER:-}}"

if [[ -n "${NEXUS_USERNAME}" && -n "${NEXUS_PASSWORD:-}" ]]; then
  registry="${DIFY_API_IMAGE%%/*}"
  echo "==> Docker login ${registry}"
  echo "${NEXUS_PASSWORD}" | docker login "${registry}" -u "${NEXUS_USERNAME}" --password-stdin
fi

# if [[ "${GIT_PULL}" == "true" && -d "${DEPLOY_PATH}/.git" ]]; then
#   echo "==> git pull ${DEPLOY_PATH}"
#   git -C "${DEPLOY_PATH}" pull --ff-only
# fi

mkdir -p "${DOCKER_DIR}"
cat > "${TAG_FILE}" <<EOF
# Generated by deploy-remote.sh
DIFY_API_IMAGE=${DIFY_API_IMAGE}
DIFY_WEB_IMAGE=${DIFY_WEB_IMAGE}
DIFY_IMAGE_TAG=${DIFY_API_IMAGE_TAG}
DIFY_API_IMAGE_TAG=${DIFY_API_IMAGE_TAG}
DIFY_WEB_IMAGE_TAG=${DIFY_WEB_IMAGE_TAG}
EOF

cd "${DOCKER_DIR}"

echo "==> Pulling images"
# shellcheck disable=SC2086
docker compose ${COMPOSE_FILE} --env-file "${TAG_FILE}" pull ${DEPLOY_SERVICES}

echo "==> Starting services"
# shellcheck disable=SC2086
docker compose ${COMPOSE_FILE} --env-file "${TAG_FILE}" up -d --force-recreate ${DEPLOY_SERVICES}

echo "Deploy complete."
# shellcheck disable=SC2086
docker compose ${COMPOSE_FILE} --env-file "${TAG_FILE}" ps ${DEPLOY_SERVICES}

